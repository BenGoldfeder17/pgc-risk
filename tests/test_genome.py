"""Genome-file parsers, on small hand-written files in each supported format."""
import gzip
import zipfile

import numpy as np
import pytest

from pgc_risk.genome import GenomeFormatError, read_genome

A, C, G, T = 0, 1, 2, 3


def calls(g):
    return {int(r): (int(a), int(b)) for r, a, b in zip(g.rsid, g.a1, g.a2)}


TWENTYTHREE = """# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2024
# We are using reference human assembly build 37 (also known as Annotation Release 104).
# rsid\tchromosome\tposition\tgenotype
rs1\t1\t1000\tAG
rs2\t1\t2000\tCC
rs3\t2\t3000\t--
rs4\t2\t4000\tDI
i5000\t3\t5000\tTT
rs6\tX\t6000\tA
rs7\tMT\t7000\tG
rs8\t22\t8000\tGT
"""


def test_23andme(tmp_path):
    p = tmp_path / "genome.txt"
    p.write_text(TWENTYTHREE)
    g = read_genome(p)
    assert (g.fmt, g.build) == ("23andme", 37)
    assert g.n == 6                                   # X and MT are dropped
    assert calls(g)[1] == (A, G) and calls(g)[2] == (C, C) and calls(g)[8] == (G, T)
    assert calls(g)[3] == (-1, -1) and calls(g)[4] == (-1, -1)   # no-call and indel
    assert g.rsid.tolist().count(-1) == 1 and int(g.called.sum()) == 4
    assert g.chrom.tolist() == [1, 1, 2, 2, 3, 22] and g.pos[0] == 1000


def test_gz_and_zip_give_the_same_calls(tmp_path):
    plain = tmp_path / "genome.txt"
    plain.write_text(TWENTYTHREE)
    gz = tmp_path / "genome.txt.gz"
    with gzip.open(gz, "wt") as fh:
        fh.write(TWENTYTHREE)
    zp = tmp_path / "genome.zip"
    with zipfile.ZipFile(zp, "w") as zf:
        zf.writestr("readme.txt", "hello")
        zf.writestr("genome_Jane_Doe_v5_Full.txt", TWENTYTHREE)
    want = calls(read_genome(plain))
    assert calls(read_genome(gz)) == want
    assert calls(read_genome(zp)) == want


def test_ancestry(tmp_path):
    p = tmp_path / "AncestryDNA.txt"
    p.write_text("#AncestryDNA raw data download\n#Data was collected using an AncestryDNA array\n"
                 "#the forward strand of human reference build 37.\n"
                 "rsid\tchromosome\tposition\tallele1\tallele2\n"
                 "rs1\t1\t1000\tA\tG\nrs2\t1\t2000\t0\t0\nrs3\t23\t3000\tC\tC\nrs4\t5\t4000\tT\tC\n")
    g = read_genome(p)
    assert g.fmt == "ancestry" and g.n == 3           # chromosome 23 (X) dropped
    assert calls(g) == {1: (A, G), 2: (-1, -1), 4: (T, C)}


def test_myheritage_csv(tmp_path):
    p = tmp_path / "MyHeritage_raw_dna_data.csv"
    p.write_text('# MyHeritage DNA raw data.\n# Human genome build 37\n'
                 'RSID,CHROMOSOME,POSITION,RESULT\n'
                 '"rs1","1","1000","AA"\n"rs2","1","2000","--"\n"rs3","7","3000","CT"\n')
    g = read_genome(p)
    assert g.fmt == "csv"
    assert calls(g) == {1: (A, A), 2: (-1, -1), 3: (C, T)}


VCF_HEAD = ("##fileformat=VCFv4.2\n##contig=<ID=chr1,length=248956422>\n"
            "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\tS2\n")


def test_vcf_variants_only(tmp_path):
    p = tmp_path / "wgs.vcf"
    p.write_text(VCF_HEAD +
                 "chr1\t1000\trs1\tA\tG\t50\tPASS\t.\tGT:DP\t0/1:30\t1/1:20\n"
                 "chr1\t2000\t.\tC\tT\t50\tPASS\t.\tGT\t1|1\t0|0\n"
                 "chr1\t3000\trs3\tG\tA,T\t50\tPASS\t.\tGT\t1/2\t0/2\n"       # multi-allelic
                 "chr1\t4000\trs4\tA\tAT\t50\tPASS\t.\tGT\t0/1\t0/1\n"        # insertion
                 "chr1\t5000\trs5\tAT\tA\t50\tPASS\t.\tGT\t0/1\t0/1\n"        # deletion: skipped
                 "chr1\t6000\trs6\tC\tG\t5\tLowQual\t.\tGT\t0/1\t0/1\n"       # filtered
                 "chr1\t7000\trs7\tT\tC\t50\t.\t.\tGT\t./.\t0/1\n"            # no call
                 "chrX\t8000\trs8\tT\tC\t50\tPASS\t.\tGT\t0/1\t0/1\n")
    g = read_genome(p)
    assert (g.fmt, g.build, g.sample) == ("vcf", 38, "S1")
    assert g.variants_only
    assert g.pos.tolist() == [1000, 2000, 3000, 4000, 6000, 7000]
    c = dict(zip(g.pos.tolist(), zip(g.a1.tolist(), g.a2.tolist())))
    assert c[1000] == (A, G) and c[2000] == (T, T) and c[3000] == (A, T)
    assert c[4000] == (-1, -1) and c[6000] == (-1, -1) and c[7000] == (-1, -1)
    assert g.rsid.tolist()[:2] == [1, -1]
    g2 = read_genome(p, sample="S2")
    c2 = dict(zip(g2.pos.tolist(), zip(g2.a1.tolist(), g2.a2.tolist())))
    assert c2[1000] == (G, G) and c2[2000] == (C, C) and c2[3000] == (G, T) and c2[7000] == (T, C)
    with pytest.raises(GenomeFormatError):
        read_genome(p, sample="nobody")


def test_vcf_all_sites_is_not_variants_only(tmp_path):
    p = tmp_path / "imputed.vcf.gz"
    body = "".join(f"1\t{1000 + i}\trs{i}\tA\tG\t.\tPASS\t.\tGT\t{'0|0' if i % 3 else '0|1'}\n"
                   for i in range(30))
    with gzip.open(p, "wt") as fh:
        fh.write("##fileformat=VCFv4.1\n##reference=file:///ref/human_g1k_v37.fasta\n"
                 "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tNA1\n" + body)
    g = read_genome(p)
    assert g.build == 37 and not g.variants_only and g.n == 30
    assert int((g.a1 == A).sum()) == 30 and int((g.a2 == G).sum()) == 10


def test_gvcf_reference_blocks(tmp_path):
    p = tmp_path / "sample.g.vcf"
    p.write_text("##fileformat=VCFv4.2\n##contig=<ID=1,length=249250621>\n"
                 "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS\n"
                 "1\t100\t.\tA\t<NON_REF>\t.\t.\tEND=199\tGT:DP\t0/0:30\n"
                 "1\t200\trs9\tC\tT,<NON_REF>\t60\t.\t.\tGT:DP\t0/1:28\n"
                 "1\t201\t.\tG\t<NON_REF>\t.\t.\tEND=500\tGT:DP\t0/0:31\n"
                 "1\t900\t.\tG\t<NON_REF>\t.\tLowQual\tEND=950\tGT:DP\t0/0:2\n")
    g = read_genome(p)
    assert g.build == 37 and not g.variants_only
    starts, ends = g.ref_blocks[1]
    assert starts.tolist() == [100, 201] and ends.tolist() == [199, 500]   # low-quality block dropped
    assert g.pos.tolist() == [200] and (int(g.a1[0]), int(g.a2[0])) == (C, T)


def test_unrecognised_file(tmp_path):
    p = tmp_path / "notes.txt"
    p.write_text("this is not a genome\nat all\n")
    with pytest.raises(GenomeFormatError):
        read_genome(p)
    with pytest.raises(GenomeFormatError):
        read_genome(tmp_path / "missing.txt")
